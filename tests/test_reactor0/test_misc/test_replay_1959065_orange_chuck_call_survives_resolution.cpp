  auto rec = nlohmann::json::parse(kSnapshotJson);
  hanabi::Game game = hanabi::logging::apply_snapshot(rec);
  const hanabi::State& s = game.state;

  ASSERT_EQ(game.convention, hanabi::Convention::REACTOR0);

  const int us = 0;                 // will-bot67
  const int dark_orange = 4;
  ASSERT_TRUE(s.variant->suits[dark_orange].suit_type.inverted);
  ASSERT_TRUE(s.variant->suits[dark_orange].suit_type.dark)
      << "Dark Orange is oneOfEach, so every card of it is critical — that is "
         "what made the non-critical narrowing empty";
  ASSERT_EQ(s.play_stacks[dark_orange], 1)
      << "the stack is at 1, so Dark Orange 2 is exactly playable";

  const int chuck_order = s.hands[us][2];   // slot 3

  // The root cause, asserted directly: the call must still be standing, and
  // the card must not have been branded trash.
  EXPECT_EQ(game.meta[chuck_order].status, hanabi::CardStatus::CALLED_TO_DISCARD)
      << "the chuck call must survive the reacter's play";
  EXPECT_FALSE(game.meta[chuck_order].trash)
      << "a chuck is a play call — 'every identity is critical' is evidence "
         "the card is irreplaceable, not evidence it is trash";

  hanabi::PerformAction action = game.take_action();

  // The symptom.
  auto* discard = std::get_if<hanabi::PerformDiscard>(&action);
  ASSERT_NE(discard, nullptr)
      << "Discard is the button that chucks an orange onto its stack";
  EXPECT_EQ(discard->target, chuck_order)
      << "slot 3 is the called Dark Orange 2; discarding slot 1 was the bug";
