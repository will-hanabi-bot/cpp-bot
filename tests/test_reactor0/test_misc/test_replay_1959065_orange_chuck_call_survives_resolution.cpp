// Replay 1959065 turn 10 (reactor0, "Chimneys & Dark Orange (5 Suits)").
// bug_report_6_2_0.txt.
//
// Turn 5: will-bot69 clues Dark Orange to will-bot67, touching only order 3.
// The target is not the giver's Bob, so this is a REACTIVE clue with
// yagami_black as reacter, and the receiver's Dark Orange target is stamped
// CALLED_TO_DISCARD — on an inverted suit that is a CHUCK, i.e. a play call.
// Turn 6: the reacter plays, resolving the connection through
// `reactor0::react_play`'s COLOUR branch into `target_i_discard`.
//
// `target_i_discard` narrowed `inferred` to the NON-CRITICAL identities. Dark
// Orange is `oneOfEach`, so every identity is critical and the set emptied:
// the card was marked `meta.trash`, and `Game::elim`'s step-1 sweep then reset
// it to global empathy and cleared the status. The chuck signal was destroyed
// one turn after it was given, and order 3 — the playable Dark Orange 2 — was
// left neither playable (`order_playable` bails on `meta.trash`) nor
// discardable (`order_trash` bails on all-critical).
//
// The visible symptom is here at turn 10: will-bot67 discarded slot 1 instead
// of chucking slot 3.
//
// Snapshot auto-generated by `replay_log --emit-test`; asserts written by hand.
// Note `apply_snapshot` replays the full action list rather than restoring the
// logged meta, so this genuinely re-executes the turn-5 clue and the turn-6
// resolution.

