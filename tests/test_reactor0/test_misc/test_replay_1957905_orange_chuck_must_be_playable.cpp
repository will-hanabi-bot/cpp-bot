  ASSERT_EQ(game.convention, hanabi::Convention::REACTOR0)
      << "the snapshot must replay under the convention the game ran";

  // Fixture sanity: the orange ladder is in chuck mode, and the card the
  // chuck would land on is the already-stacked Orange 1.
  const int orange = 3;
  ASSERT_TRUE(s.variant->suits[orange].suit_type.inverted);
  ASSERT_LE(s.pace(), 3) << "pace <= 3 is what selects the chuck branch";
  const int yagami = 1;
  const int leftmost_orange = s.hands[yagami][0];
  auto leftmost_id = s.deck[leftmost_orange].id();
